/*
 * Seating Plan Routes
 *
 * GET    /api/seating-plans              — list all seating plans
 * GET    /api/seating-plans/:id          — get a single plan
 * GET    /api/seating-plans/exam/:examId — get plan for a specific exam
 * POST   /api/seating-plans              — save a generated plan (teacher)
 * PUT    /api/seating-plans/:id/finalize — finalize a plan (teacher)
 * DELETE /api/seating-plans/:id          — delete a plan (teacher)
 *
 * The actual seating algorithm (seating-algorithm.js) still runs on the frontend.
 * The teacher generates the plan in the browser, then POSTs the result here to
 * persist it in MongoDB. This keeps the algorithm in the frontend bundle just
 * as it was in ST1, while moving storage to the database.
 *
 * All read routes: requireAuth (teacher + student)
 * Write routes: requireAuth + requireRole("teacher")
 */

"use strict";

const express      = require("express");
const SeatingPlan  = require("../models/SeatingPlan");
const { requireAuth, requireRole } = require("../middleware/auth");

const router = express.Router();

const teacherOnly = [requireAuth, requireRole("teacher")];


/* -------------------------------------------------------
   GET /api/seating-plans
   ------------------------------------------------------- */

router.get("/", requireAuth, async function (req, res) {

  try {
    const plans = await SeatingPlan.find().sort({ generatedAt: -1 });
    return res.status(200).json({ seatingPlans: plans });
  } catch (error) {
    console.error("Get seating plans error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


/* -------------------------------------------------------
   GET /api/seating-plans/exam/:examId
   Returns the most-recent plan for a given exam.
   ------------------------------------------------------- */

router.get("/exam/:examId", requireAuth, async function (req, res) {

  try {
    const plan = await SeatingPlan
      .findOne({ examId: req.params.examId })
      .sort({ generatedAt: -1 });

    if (!plan) {
      return res.status(404).json({ message: "No seating plan found for this examination." });
    }

    return res.status(200).json({ seatingPlan: plan });

  } catch (error) {
    console.error("Get plan by exam error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


/* -------------------------------------------------------
   GET /api/seating-plans/:id
   ------------------------------------------------------- */

router.get("/:id", requireAuth, async function (req, res) {

  try {
    const plan = await SeatingPlan.findById(req.params.id);
    if (!plan) {
      return res.status(404).json({ message: "Seating plan not found." });
    }
    return res.status(200).json({ seatingPlan: plan });
  } catch (error) {
    console.error("Get seating plan error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


/* -------------------------------------------------------
   POST /api/seating-plans
   Save a plan generated by the frontend algorithm.

   Body: the full plan object produced by ExamSeatSeatingAlgorithm.createPlan()
   ------------------------------------------------------- */

router.post("/", ...teacherOnly, async function (req, res) {

  try {

    const planData = req.body;

    if (!planData || !planData.examId) {
      return res.status(400).json({ message: "examId is required." });
    }

    /* Replace any existing Generated plan for this exam */
    await SeatingPlan.deleteOne({ examId: planData.examId, status: "Generated" });

    const plan = new SeatingPlan({
      examId:               planData.examId,
      status:               planData.status || "Generated",
      generatedAt:          planData.generatedAt || new Date().toISOString(),
      studentCount:         planData.studentCount,
      capacity:             planData.capacity,
      constraints:          planData.constraints,
      rooms:                planData.rooms,
      assignments:          planData.assignments,
      unassignedStudentIds: planData.unassignedStudentIds || []
    });

    await plan.save();

    return res.status(201).json({ seatingPlan: plan });

  } catch (error) {
    console.error("Save seating plan error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


/* -------------------------------------------------------
   PUT /api/seating-plans/:id/finalize
   Sets a plan's status to "Finalized".
   Mirrors confirmFinalizeSeatingPlan() in teacher.js.
   ------------------------------------------------------- */

router.put("/:id/finalize", ...teacherOnly, async function (req, res) {

  try {

    const plan = await SeatingPlan.findById(req.params.id);

    if (!plan) {
      return res.status(404).json({ message: "Seating plan not found." });
    }

    if (plan.status === "Finalized") {
      return res.status(400).json({ message: "Plan is already finalized." });
    }

    plan.status = "Finalized";
    await plan.save();

    return res.status(200).json({ seatingPlan: plan });

  } catch (error) {
    console.error("Finalize plan error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


/* -------------------------------------------------------
   DELETE /api/seating-plans/:id
   ------------------------------------------------------- */

router.delete("/:id", ...teacherOnly, async function (req, res) {

  try {

    const plan = await SeatingPlan.findByIdAndDelete(req.params.id);

    if (!plan) {
      return res.status(404).json({ message: "Seating plan not found." });
    }

    return res.status(200).json({ message: "Seating plan deleted." });

  } catch (error) {
    console.error("Delete seating plan error:", error);
    return res.status(500).json({ message: "Server error." });
  }

});


module.exports = router;
